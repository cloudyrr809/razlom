"""Гладкие меши крипа: ножка и шляпка (файлы .obj для импорта в Roblox Studio).

Числа формы берутся из src/shared/Config.luau (CreepLooks), формулы повторяют
Models.stemRadius / capTop / capBottom — чтобы глаза и трещины ложились на поверхность.

Запуск:  python tools/creep_meshes.py   ->  tools/meshes/CreepStem.obj, CreepCap.obj
"""

import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = (ROOT / "src" / "shared" / "Config.luau").read_text(encoding="utf-8")
OUT = ROOT / "tools" / "meshes"


def nums(name: str) -> list[float]:
    """Все числа из строки `name = ...` в Config.luau (до комментария)."""
    m = re.search(rf"^\s*{name}\s*=\s*(.+?)(?:--.*)?$", CONFIG, re.M)
    if not m:
        raise SystemExit(f"В Config.luau нет {name}")
    return [float(x) for x in re.findall(r"-?\d+(?:\.\d+)?", m.group(1))]


flat = nums("StemProfile")
PROFILE = [(flat[i], flat[i + 1]) for i in range(0, len(flat), 2)]
DOME = nums("CapDome")
BRIM = nums("CapBrim")
SMOOTH = nums("CapSmooth")[0]
UNDER = nums("CapUnder")[0]
WAVE_COUNT, WAVE_AMP = nums("CapWave")


def stem_radius(u: float) -> float:
    """Как Models.stemRadius: кубическая кривая Эрмита через точки профиля."""
    p = PROFILE
    u = min(max(u, 0.0), 1.0)
    i = 0
    while i < len(p) - 2 and u > p[i + 1][0]:
        i += 1

    def slope(j: int) -> float:
        a, b = p[max(0, j - 1)], p[min(len(p) - 1, j + 1)]
        return (b[1] - a[1]) / (b[0] - a[0])

    (u0, r0), (u1, r1) = p[i], p[i + 1]
    span = u1 - u0
    t = (u - u0) / span
    t2, t3 = t * t, t * t * t
    return ((2 * t3 - 3 * t2 + 1) * r0 + (t3 - 2 * t2 + t) * span * slope(i)
            + (-2 * t3 + 3 * t2) * r1 + (t3 - t2) * span * slope(i + 1))


def cap_top(k: float) -> float:
    d1, d2, d3 = DOME
    b1, b2, b3 = BRIM
    dome = d1 + d3 * math.sqrt(1 - (k / d2) ** 2) if k < d2 else d1 - (k - d2) * 4
    brim = b1 + b3 * math.sqrt(max(0.0, 1 - (k / b2) ** 2))
    return 0.5 * (dome + brim + math.sqrt((dome - brim) ** 2 + SMOOTH * SMOOTH))


def cap_bottom(k: float) -> float:
    b1, b2, b3 = BRIM
    return b1 - b3 * UNDER * math.sqrt(max(0.0, 1 - (k / b2) ** 2))


def lathe(profile: list[tuple[float, float]], segments: int, wave=None):
    """Тело вращения: profile — точки (радиус, высота) сверху вниз по контуру.
    Точки с радиусом 0 — полюса (одна вершина). wave(k, angle) -> множитель радиуса."""
    verts, faces = [], []
    rings = []
    for r, y in profile:
        if r < 1e-6:
            verts.append((0.0, y, 0.0))
            rings.append([len(verts)] * segments)
            continue
        ring = []
        for s in range(segments):
            a = s / segments * math.tau
            rr = r * (wave(r, a) if wave else 1.0)
            verts.append((math.sin(a) * rr, y, -math.cos(a) * rr))
            ring.append(len(verts))
        rings.append(ring)
    for j in range(len(rings) - 1):
        a, b = rings[j], rings[j + 1]
        for s in range(segments):
            s2 = (s + 1) % segments
            quad = [a[s], a[s2], b[s2], b[s]]
            tri1, tri2 = (quad[0], quad[1], quad[2]), (quad[0], quad[2], quad[3])
            for tri in (tri1, tri2):
                if len(set(tri)) == 3:
                    faces.append(tri)
    return verts, faces


def write_obj(path: Path, verts, faces, center: tuple[float, float, float]):
    """Сглаженные нормали (среднее по граням), вершины сдвинуты к центру рамки."""
    n = [[0.0, 0.0, 0.0] for _ in verts]
    for f in faces:
        p0, p1, p2 = (verts[i - 1] for i in f)
        ux, uy, uz = p1[0] - p0[0], p1[1] - p0[1], p1[2] - p0[2]
        vx, vy, vz = p2[0] - p0[0], p2[1] - p0[1], p2[2] - p0[2]
        cx, cy, cz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
        for i in f:
            n[i - 1][0] += cx
            n[i - 1][1] += cy
            n[i - 1][2] += cz
    # Грани должны смотреть наружу: если средняя нормаль смотрит внутрь — переворачиваем.
    out = sum(n[i][0] * (verts[i][0] - center[0]) + n[i][2] * (verts[i][2] - center[2]) for i in range(len(verts)))
    flip = out < 0
    lines = ["# Razlom creep mesh, generated by tools/creep_meshes.py"]
    for v in verts:
        lines.append(f"v {v[0] - center[0]:.5f} {v[1] - center[1]:.5f} {v[2] - center[2]:.5f}")
    for v in n:
        length = math.sqrt(v[0] ** 2 + v[1] ** 2 + v[2] ** 2) or 1.0
        k = -1.0 if flip else 1.0
        lines.append(f"vn {k * v[0] / length:.5f} {k * v[1] / length:.5f} {k * v[2] / length:.5f}")
    for f in faces:
        f = (f[0], f[2], f[1]) if flip else f
        lines.append("f " + " ".join(f"{i}//{i}" for i in f))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{path.relative_to(ROOT)}: {len(verts)} вершин, {len(faces)} треугольников")


def smoothstep_samples(count: int, power: float = 1.0) -> list[float]:
    return [(i / count) ** power for i in range(count + 1)]


def build_stem():
    # Высота ножки — 1, ширина — по профилю (радиус крипа = 1). Сверху вниз: крышка, бок, дно.
    rows = 48
    prof = [(0.0, 1.0)]
    for i in range(rows, -1, -1):
        u = i / rows
        prof.append((stem_radius(u), u))
    prof.append((0.0, 0.0))
    verts, faces = lathe(prof, 40)
    write_obj(OUT / "CreepStem.obj", verts, faces, (0.0, 0.5, 0.0))


def build_cap():
    # Радиус шляпки — 1, высота — 1. Сверху от макушки к краю, потом по низу обратно к оси.
    b2 = BRIM[1]
    top = [(b2 * k, cap_top(b2 * k)) for k in smoothstep_samples(40, 0.8)]
    bottom = [(b2 * k, cap_bottom(b2 * k)) for k in reversed(smoothstep_samples(24, 0.8))]
    # Самый край — скруглённая губа: последние точки верха и низа уже сходятся на k = 1.
    prof = [(0.0, top[0][1])] + top[1:] + bottom[1:-1] + [(0.0, bottom[-1][1])]

    def wave(r: float, a: float) -> float:
        k = r / b2
        return 1.0 + WAVE_AMP * math.sin(WAVE_COUNT * a) * k ** 4

    verts, faces = lathe(prof, 64, wave)
    y0, y1 = cap_bottom(0.0), cap_top(0.0)
    write_obj(OUT / "CreepCap.obj", verts, faces, (0.0, (y0 + y1) / 2, 0.0))


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    build_stem()
    build_cap()
